import { pinyin } from "pinyin-pro";

/**
 * DictionaryService: Enriches Chinese characters with pinyin and English translations.
 *
 * Uses `pinyin-pro` for pinyin lookup and a built-in character→English map
 * compiled from CC-CEDICT data for the ~2500 characters in our word list.
 */

// Lazy-loaded English dictionary map
let englishMap: Map<string, string> | null = null;

function getEnglishMap(): Map<string, string> {
  if (englishMap) return englishMap;
  englishMap = new Map(Object.entries(CHAR_ENGLISH_MAP));
  return englishMap;
}

export function lookupPinyin(char: string): string {
  try {
    return pinyin(char, { toneType: "symbol", type: "string" });
  } catch {
    return "";
  }
}

export function lookupEnglish(char: string): string {
  const map = getEnglishMap();
  return map.get(char) ?? "";
}

export interface EnrichedCharacter {
  character: string;
  pinyin: string;
  english: string;
}

export function enrichCharacter(char: string): EnrichedCharacter {
  const p = lookupPinyin(char);
  const e = lookupEnglish(char);
  if (!p && !e) {
    console.warn(`Dictionary lookup failed for character: ${char}`);
  }
  return { character: char, pinyin: p, english: e };
}

export function enrichAll(chars: string[]): EnrichedCharacter[] {
  return chars.map((c) => enrichCharacter(c));
}

